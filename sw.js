// ДВА ОСОЗНАННЫХ ИСКЛЮЧЕНИЯ. Оба НЕ забыты - выведены намеренно, у обоих
// цена включения выше выигрыша. Не добавлять обратно, не прочитав причину.
//
// glutes: прогресс тренировок лежит в glutes_progress_v1 (glutes/storage.js:18),
//   и на ВЕБЕ это localStorage - боевой CloudStorage работает только внутри
//   телеграма. Под /glutes/ открылось бы ПУСТОЕ хранилище нашего origin, а
//   старое на github.io стало бы недостижимо навсегда: женщина потеряла бы
//   отметки МОЛЧА. Мост для переноса требует правки glutes/index.html, то есть
//   релиза в телеграм-дверь. ВЕРНУТЬ можно после переезда прогресса на сервер.
//
// bodyage: читает общий ключ темы irena_theme (bodyage/index.html:13), а наш
//   index.html:14 этот ключ ЗАТИРАЕТ при значении 'light'. Под /bodyage/ они
//   оказались бы в одном хранилище, и выбор темы перестал бы запоминаться -
//   сбрасывался бы при каждом возврате на дом. Раздражает постоянно, а плитка
//   редкая: размен невыгодный. ВЕРНУТЬ можно после того, как bodyage перейдёт
//   на свой ключ темы.
//
// studio: ЖИВАЯ ПОЛОМКА, воспроизведена 2026-08-18 дважды на iPhone и в браузере.
//   Кнопка «← В студию» в медитациях (meditation/index.html:757-766) читает токен
//   из localStorage СИНХРОННО, на строку РАНЬШЕ, чем irenaCheckAccess (строка 767)
//   успевает записать туда свежий. Пока studio жила на github.io, она сама обновляла
//   это хранилище при каждом заходе, и кнопка видела свежий токен. С нашего origin
//   studio в github.io больше не пишет - и кнопка забирает ОСТАТОК ПРОШЛОЙ СЕССИИ.
//   Дальше Math.max(1, ...) превращает протухший срок в exp=1, студия по возврату
//   ПЕРЕЗАПИСЫВАЕТ им свежий токен, и он умирает через секунду -> «Доступ закрыт»,
//   no_web_token. Медитация при этом играет: она-то токен получила.
//   Починка требует правки медитаций или самой студии - файлов ОБЕИХ дверей.
//   ВЕРНУТЬ можно только вместе с этим (или вариантом C: патч разметки в воркере).
//
// Плата за исключения одна: эти плитки продолжают вылетать в Safari на iOS.
const MINI = [
  "workout", "cycle",
  "breathing", "breathing446", "meditation", "sleep-meditation",
  "anxiety-meditation", "slim-meditation", "kids-meditation",
  "mitochondria-meditation", "ideal-reality", "burning-meditation",
  "control-meditation", "oneday",
];

const GH = "https://vladlen00.github.io";

// Медиа отдаём РЕДИРЕКТОМ, а не проксированием. Range-запросы через воркер
// отдаются целиком, и перемотка 33-мегабайтного mp3 в студии умерла бы.
// Cross-origin ПОДРЕСУРС из standalone не выбрасывает - выбрасывает только
// навигация документа, а её мы как раз и оставляем своей.
const MEDIA = /\.(mp3|m4a|mp4|webm|ogg|wav|webp|png|jpe?g|gif|svg|woff2?|ttf|pdf)$/i;

self.addEventListener("install", () => self.skipWaiting());

// clients.claim(): берём контроль над УЖЕ открытой страницей, без перезагрузки.
// Без него первый заход после установки шёл бы по откату на github.io.
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

self.addEventListener("fetch", (e) => {
  const u = new URL(e.request.url);

  // Чужие хосты не наше дело: Supabase, Kinescope, шрифты, Подружка.
  if (u.origin !== self.location.origin) return;

  // ВОТ ЗДЕСЬ ДЕЙСТВУЕТ ПРАВИЛО. Первый сегмент пути обязан быть мини-аппом
  // из списка. Всё остальное - "/", "/app.js", "/style.css", "/covers/...",
  // "/icons/..." - проходит мимо воркера напрямую на GitHub Pages.
  const seg = u.pathname.split("/")[1];
  if (!MINI.includes(seg)) return;

  if (MEDIA.test(u.pathname)) {
    e.respondWith(Response.redirect(GH + u.pathname + u.search, 302));
    return;
  }

  // credentials: "omit" обязателен: с ACAO "*" браузер отвергает ответ на
  // запрос с учётными данными. Их тут и не нужно - Pages отдаёт статику.
  // .catch(): если проксирование не сложилось, уводим на github.io напрямую,
  // то есть в СЕГОДНЯШНЕЕ поведение. Хуже, чем без воркера, не становится.
  e.respondWith(
    fetch(GH + u.pathname + u.search, { credentials: "omit" })
      .catch(() => Response.redirect(GH + u.pathname + u.search, 302))
  );
});
